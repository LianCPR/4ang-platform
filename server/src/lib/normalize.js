export function removeDiacritics(str) {
  if (!str) return '';
  return str.split('').map(c => VIET_MAP[c] || c).join('').toLowerCase();
}

export function normalizeSearch(query) {
  if (!query) return '';
  return removeDiacritics(query).replace(/\s+/g, ' ').trim();
}
